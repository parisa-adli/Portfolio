// Drives the hero keyboard: tech-key hover, typing a secret word, and a mid-wave screenshot.
import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await p.goto("http://localhost:3000/a", { waitUntil: "networkidle" });
await p.waitForTimeout(800);
await p.hover('.key[data-code="Tech0"]', { force: true });
await p.waitForTimeout(400);
console.log("tip:", await p.locator("[data-kb-tip]").textContent(), await p.locator("[data-kb-tip]").getAttribute("class"));
await p.screenshot({ path: "screenshots/s5-tip.png", clip: { x: 640, y: 200, width: 800, height: 500 } });
await p.mouse.move(300, 300);
await p.keyboard.down("KeyH");
console.log("down class:", await p.locator('.key[data-code="KeyH"]').getAttribute("class"));
await p.keyboard.up("KeyH");
await p.keyboard.type("ire");
await p.waitForTimeout(350);
console.log("screen:", await p.locator("[data-kb-screen]").textContent());
console.log("toast:", await p.locator(".toast").textContent().catch(() => "none"));
await p.screenshot({ path: "screenshots/s5-wave.png" });
await p.click(".sound-toggle", { force: true });
console.log("sound pressed:", await p.locator(".sound-toggle").getAttribute("aria-pressed"));
await p.keyboard.press("KeyA");
console.log("errors:", errors.join(" | ") || "none");
await b.close();
